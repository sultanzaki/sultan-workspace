import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

// The SQL Editor path records exactly the same checksums as npm run db:migrate.
export async function migrationSql() {
  const directory = new URL('../server/migrations/', import.meta.url);
  const files = (await readdir(directory)).filter(file => file.endsWith('.sql')).sort();
  const blocks = [];
  for (const file of files) {
    if (!/^[a-zA-Z0-9_.-]+$/.test(file)) throw new Error('Unsupported migration filename');
    const sql = await readFile(new URL(file, directory), 'utf8');
    const checksum = createHash('sha256').update(sql).digest('hex');
    if (sql.includes('$migration_body$') || sql.includes('$migration_runner$')) throw new Error('Migration contains reserved export delimiter');
    blocks.push(`DO $migration_runner$
DECLARE applied_checksum text;
BEGIN
  SELECT checksum INTO applied_checksum FROM app_private.schema_migrations WHERE name = '${file}';
  IF applied_checksum IS NULL THEN
    EXECUTE $migration_body$${sql}$migration_body$;
    INSERT INTO app_private.schema_migrations(name, checksum) VALUES ('${file}', '${checksum}');
  ELSIF applied_checksum <> '${checksum}' THEN
    RAISE EXCEPTION 'Applied migration changed: ${file}';
  END IF;
END
$migration_runner$;`);
  }
  return `-- Generated by npm run db:export. Do not edit this file manually.
-- Supabase: SQL Editor > New query > paste the entire file > Run.
-- Creates application tables only in app_private; does not delete existing data.
-- Safe to run again: already-recorded migrations are skipped after checksum verification.
BEGIN;
DO $migration_lock$ BEGIN PERFORM pg_advisory_xact_lock(84291370); END $migration_lock$;
CREATE SCHEMA IF NOT EXISTS app_private;
SET LOCAL search_path = app_private;
CREATE TABLE IF NOT EXISTS schema_migrations (name text PRIMARY KEY, checksum text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now());

${blocks.join('\n\n')}

COMMIT;

-- Supabase SQL Editor displays this status instead of the lock's empty result.
SELECT name, applied_at FROM app_private.schema_migrations ORDER BY name;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.stdout.write(await migrationSql());
